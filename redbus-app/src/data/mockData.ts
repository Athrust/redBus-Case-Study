export const GENERATE_SEATS = (baseFare: number): Seat[] => {
  const seats: Seat[] = [];
  
  // 16 seats - 2+2 layout standard for short distances
  const rows = 4;
  for (let r = 1; r <= rows; r++) {
    seats.push({
      id: `L-${r}A`,
      number: `${r}A`,
      deck: 'lower',
      type: 'seater',
      row: r,
      col: 1,
      fare: baseFare,
      status: r === 2 ? 'booked' : r === 4 ? 'ladies' : 'available'
    });
    seats.push({
      id: `L-${r}B`,
      number: `${r}B`,
      deck: 'lower',
      type: 'seater',
      row: r,
      col: 2,
      fare: baseFare,
      status: r === 1 ? 'booked' : 'available'
    });
    seats.push({
      id: `L-${r}C`,
      number: `${r}C`,
      deck: 'lower',
      type: 'seater',
      row: r,
      col: 3,
      fare: baseFare,
      status: r === 3 ? 'booked' : 'available'
    });
    seats.push({
      id: `L-${r}D`,
      number: `${r}D`,
      deck: 'lower',
      type: 'seater',
      row: r,
      col: 4,
      fare: baseFare,
      status: 'available'
    });
  }

  return seats;
};
